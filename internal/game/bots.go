func (LocalBot) Describe(_ context.Context, in BotInput) (string, error) {
	xs := clues[in.Word]
	if len(xs) == 0 {
		return "它在日常生活里很常见，也有自己独特的用途。", nil
	}
	seed := sha256.Sum256([]byte(in.PlayerID))
	return xs[(in.Round-1+int(seed[0]))%len(xs)], nil
}
func (LocalBot) Vote(_ context.Context, in BotInput) (string, error) {
	if len(in.Targets) == 0 {
		return "", nil
	}
	sum := sha256.Sum256([]byte(in.PlayerID + fmt.Sprint(in.Round) + in.Phase + fmt.Sprint(len(in.Speeches))))
	return in.Targets[int(sum[0])%len(in.Targets)], nil
}
